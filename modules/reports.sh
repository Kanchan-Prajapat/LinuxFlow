#!/bin/bash

############################################
# LinuxFlow - Report Generator Module
############################################


##################################################
# Report Directory
##################################################

REPORT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/reports"


##################################################
# Function : initialize_report_directory
# Purpose  : Create report directory if required
##################################################

initialize_report_directory() {

    if [ ! -d "$REPORT_DIR" ]; then

        if ! mkdir -p "$REPORT_DIR"; then
            error "Unable to create report directory."
            return 1
        fi

    fi

    return 0
}


##################################################
# Function : generate_report_name
# Purpose  : Generate unique report filename
##################################################

generate_report_name() {

    local report_type="$1"
    local timestamp
    local filename
    local counter=1

    timestamp=$(date +"%Y%m%d_%H%M%S")

    filename="linuxflow_${report_type}_${timestamp}.txt"

    while [ -e "$REPORT_DIR/$filename" ]; do
        filename="linuxflow_${report_type}_${timestamp}_${counter}.txt"
        ((counter++))
    done

    echo "$filename"
}

##################################################
# Function : generate_system_report
# Purpose  : Generate system summary report
##################################################

generate_system_report() {

    header

    echo "========== Generate System Report =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi

    report_name=$(generate_report_name "system")
    report_file="$REPORT_DIR/$report_name"

    echo "Report Type : System Summary"
    echo "Report File : $report_file"
    echo

    read -p "Generate system report? (Y/N): " confirm

    case "$confirm" in

        Y|y)
            ;;

        N|n)
            warning "Report generation cancelled."
            pause
            return
            ;;

        *)
            error "Invalid choice."
            pause
            return
            ;;
    esac


    ##################################################
    # Generate Report
    ##################################################

    {

        echo "============================================================"
        echo "                 LinuxFlow System Report"
        echo "============================================================"
        echo

        echo "Generated On : $(date '+%d-%m-%Y %H:%M:%S')"
        echo "Generated By : $(whoami)"

        echo
        echo "============================================================"
        echo " SYSTEM INFORMATION"
        echo "============================================================"
        echo

        echo "Hostname       : $(hostname)"
        echo "Kernel         : $(uname -r)"
        echo "Architecture   : $(uname -m)"

        if [ -f /etc/os-release ]; then

            os_name=$(awk -F= '
                /^PRETTY_NAME=/ {
                    gsub(/"/,"",$2)
                    print $2
                }
            ' /etc/os-release)

            echo "Operating System : ${os_name:-Unknown}"

        else
            echo "Operating System : Unknown"
        fi


        ##################################################
        # Uptime
        ##################################################

        echo
        echo "============================================================"
        echo " UPTIME"
        echo "============================================================"
        echo

        echo "Uptime : $(uptime -p 2>/dev/null || uptime)"


        ##################################################
        # CPU Information
        ##################################################

        echo
        echo "============================================================"
        echo " CPU INFORMATION"
        echo "============================================================"
        echo

        echo "CPU Cores : $(nproc 2>/dev/null || echo "Unknown")"

        cpu_model=$(awk -F: '
            /model name/ {
                gsub(/^[ \t]+/, "", $2)
                print $2
                exit
            }
        ' /proc/cpuinfo 2>/dev/null)

        echo "CPU Model : ${cpu_model:-Unknown}"

        if [ -r /proc/loadavg ]; then

            read -r load1 load5 load15 _ < /proc/loadavg

            echo "Load Average (1 min)  : $load1"
            echo "Load Average (5 min)  : $load5"
            echo "Load Average (15 min) : $load15"

        fi


        ##################################################
        # Memory Information
        ##################################################

        echo
        echo "============================================================"
        echo " MEMORY INFORMATION"
        echo "============================================================"
        echo

        free -h


        ##################################################
        # Disk Information
        ##################################################

        echo
        echo "============================================================"
        echo " DISK USAGE"
        echo "============================================================"
        echo

        df -hP \
            -x tmpfs \
            -x devtmpfs \
            -x iso9660 \
            -x squashfs \
            -x overlay \
            2>/dev/null


        ##################################################
        # Block Devices
        ##################################################

        echo
        echo "============================================================"
        echo " BLOCK DEVICES"
        echo "============================================================"
        echo

        if command -v lsblk &>/dev/null; then

            lsblk -o NAME,SIZE,TYPE,FSTYPE,MOUNTPOINTS

        else

            echo "lsblk command is not available."

        fi


        ##################################################
        # Network Information
        ##################################################

        echo
        echo "============================================================"
        echo " NETWORK INFORMATION"
        echo "============================================================"
        echo

        if command -v ip &>/dev/null; then

            echo "IP Addresses:"
            echo "------------------------------------------------------------"

            ip -brief address 2>/dev/null

            echo
            echo "Default Route:"
            echo "------------------------------------------------------------"

            ip route show default 2>/dev/null

        else

            echo "'ip' command is not available."

        fi


        ##################################################
        # Logged In Users
        ##################################################

        echo
        echo "============================================================"
        echo " LOGGED IN USERS"
        echo "============================================================"
        echo

        if command -v who &>/dev/null; then

            who

        else

            echo "'who' command is not available."

        fi


        ##################################################
        # Report Footer
        ##################################################

        echo
        echo "============================================================"
        echo "               End of System Report"
        echo "============================================================"

    } > "$report_file" 2>&1


    ##################################################
    # Verify Report
    ##################################################

    if [ ! -f "$report_file" ]; then

        error "System report could not be created."
        pause
        return

    fi

    if [ ! -s "$report_file" ]; then

        error "Generated report is empty."
        rm -f "$report_file"
        pause
        return

    fi


    ##################################################
    # Success Information
    ##################################################

    report_size=$(du -h "$report_file" |
        awk '{print $1}')

    echo
    success "System report generated successfully."

    echo
    echo "Report Name : $report_name"
    echo "Report Path : $report_file"
    echo "Report Size : $report_size"

    pause
}



##################################################
# Function : generate_user_group_report
# Purpose  : Generate users and groups report
##################################################

generate_user_group_report() {

    header

    echo "========== Generate User & Group Report =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi

    report_name=$(generate_report_name "users_groups")
    report_file="$REPORT_DIR/$report_name"

    echo "Report Type : User & Group"
    echo "Report File : $report_file"
    echo

    read -p "Generate user & group report? (Y/N): " confirm

    case "$confirm" in

        Y|y)
            ;;

        N|n)
            warning "Report generation cancelled."
            pause
            return
            ;;

        *)
            error "Invalid choice."
            pause
            return
            ;;
    esac


    ##################################################
    # Generate Report
    ##################################################

    {

        echo "============================================================"
        echo "              LinuxFlow User & Group Report"
        echo "============================================================"
        echo

        echo "Generated On : $(date '+%d-%m-%Y %H:%M:%S')"
        echo "Generated By : $(whoami)"


        ##################################################
        # Normal Users
        ##################################################

        echo
        echo "============================================================"
        echo " NORMAL USERS"
        echo "============================================================"
        echo

        printf "%-20s %-10s %-10s %-25s %s\n" \
            "USERNAME" "UID" "GID" "HOME" "SHELL"

        printf "%-20s %-10s %-10s %-25s %s\n" \
            "--------------------" \
            "----------" \
            "----------" \
            "-------------------------" \
            "--------------------"

        awk -F: '
            $3 >= 1000 && $3 < 65534 {
                printf "%-20s %-10s %-10s %-25s %s\n",
                $1, $3, $4, $6, $7
            }
        ' /etc/passwd

        total_users=$(awk -F: '
            $3 >= 1000 && $3 < 65534 {
                count++
            }

            END {
                print count+0
            }
        ' /etc/passwd)

        echo
        echo "Total Normal Users : $total_users"


        ##################################################
        # Locked User Accounts
        ##################################################

        echo
        echo "============================================================"
        echo " LOCKED USER ACCOUNTS"
        echo "============================================================"
        echo

        locked_count=0

        while IFS=: read -r username _ uid _ _
        do

            if [ "$uid" -lt 1000 ] ||
               [ "$uid" -ge 65534 ]; then
                continue
            fi

            password_status=$(passwd -S "$username" 2>/dev/null |
                awk '{print $2}')

            if [ "$password_status" = "L" ] ||
               [ "$password_status" = "LK" ]; then

                echo "$username"
                ((locked_count++))
            fi

        done < /etc/passwd

        if [ "$locked_count" -eq 0 ]; then
            echo "No locked normal user accounts found."
        fi

        echo
        echo "Total Locked Users : $locked_count"


        ##################################################
        # Current Logged In Users
        ##################################################

        echo
        echo "============================================================"
        echo " CURRENT LOGGED IN USERS"
        echo "============================================================"
        echo

        if command -v who &>/dev/null; then

            login_data=$(who 2>/dev/null)

            if [ -n "$login_data" ]; then
                echo "$login_data"
            else
                echo "No active login sessions."
            fi

        else

            echo "'who' command is not available."

        fi


        ##################################################
        # Groups
        ##################################################

        echo
        echo "============================================================"
        echo " GROUPS"
        echo "============================================================"
        echo

        printf "%-25s %-10s %s\n" \
            "GROUP NAME" "GID" "MEMBERS"

        printf "%-25s %-10s %s\n" \
            "-------------------------" \
            "----------" \
            "------------------------------"

        awk -F: '{
            members=$4

            if (members == "")
                members="None"

            printf "%-25s %-10s %s\n",
            $1, $3, members
        }' /etc/group

        total_groups=$(awk -F: '
            END {
                print NR
            }
        ' /etc/group)

        echo
        echo "Total Groups : $total_groups"


        ##################################################
        # Administrative Users
        ##################################################

        echo
        echo "============================================================"
        echo " ADMINISTRATIVE USERS"
        echo "============================================================"
        echo

        admin_group=""

        if getent group wheel &>/dev/null; then

            admin_group="wheel"

        elif getent group sudo &>/dev/null; then

            admin_group="sudo"

        fi

        if [ -n "$admin_group" ]; then

            echo "Administrative Group : $admin_group"
            echo

            admin_members=$(getent group "$admin_group" |
                awk -F: '{print $4}')

            if [ -n "$admin_members" ]; then

                echo "Members:"
                echo "$admin_members" |
                    tr ',' '\n'

            else

                echo "No supplementary members found."

            fi

        else

            echo "No wheel/sudo administrative group detected."

        fi


        ##################################################
        # Users and Their Groups
        ##################################################

        echo
        echo "============================================================"
        echo " USER GROUP MEMBERSHIP"
        echo "============================================================"
        echo

        while IFS=: read -r username _ uid _ _
        do

            if [ "$uid" -ge 1000 ] &&
               [ "$uid" -lt 65534 ]; then

                echo "$username : $(id -nG "$username" 2>/dev/null)"

            fi

        done < /etc/passwd


        ##################################################
        # Report Footer
        ##################################################

        echo
        echo "============================================================"
        echo "             End of User & Group Report"
        echo "============================================================"

    } > "$report_file" 2>&1


    ##################################################
    # Verify Report
    ##################################################

    if [ ! -f "$report_file" ]; then

        error "User & group report could not be created."
        pause
        return

    fi

    if [ ! -s "$report_file" ]; then

        error "Generated report is empty."
        rm -f "$report_file"
        pause
        return

    fi


    ##################################################
    # Report Information
    ##################################################

    report_size=$(du -h "$report_file" |
        awk '{print $1}')

    echo
    success "User & group report generated successfully."

    echo
    echo "Report Name : $report_name"
    echo "Report Path : $report_file"
    echo "Report Size : $report_size"

    pause
}


##################################################
# Function : generate_storage_report
# Purpose  : Generate storage and filesystem report
##################################################

generate_storage_report() {

    header

    echo "========== Generate Storage Report =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi

    report_name=$(generate_report_name "storage")
    report_file="$REPORT_DIR/$report_name"

    echo "Report Type : Storage"
    echo "Report File : $report_file"
    echo

    read -p "Generate storage report? (Y/N): " confirm

    case "$confirm" in

        Y|y)
            ;;

        N|n)
            warning "Report generation cancelled."
            pause
            return
            ;;

        *)
            error "Invalid choice."
            pause
            return
            ;;
    esac


    ##################################################
    # Generate Report
    ##################################################

    {

        echo "============================================================"
        echo "                LinuxFlow Storage Report"
        echo "============================================================"
        echo

        echo "Generated On : $(date '+%d-%m-%Y %H:%M:%S')"
        echo "Generated By : $(whoami)"


        ##################################################
        # Block Devices
        ##################################################

        echo
        echo "============================================================"
        echo " BLOCK DEVICES"
        echo "============================================================"
        echo

        if command -v lsblk &>/dev/null; then

            lsblk -o \
                NAME,SIZE,TYPE,FSTYPE,FSAVAIL,FSUSE%,MOUNTPOINTS

        else

            echo "'lsblk' command is not available."

        fi


        ##################################################
        # Disk Usage
        ##################################################

        echo
        echo "============================================================"
        echo " FILESYSTEM DISK USAGE"
        echo "============================================================"
        echo

        df -hP \
            -x tmpfs \
            -x devtmpfs \
            -x iso9660 \
            -x squashfs \
            -x overlay \
            2>/dev/null


        ##################################################
        # Mounted Filesystems
        ##################################################

        echo
        echo "============================================================"
        echo " MOUNTED FILESYSTEMS"
        echo "============================================================"
        echo

        if command -v findmnt &>/dev/null; then

            findmnt \
                -o TARGET,SOURCE,FSTYPE,OPTIONS

        else

            mount

        fi


        ##################################################
        # Physical Volumes
        ##################################################

        echo
        echo "============================================================"
        echo " LVM - PHYSICAL VOLUMES"
        echo "============================================================"
        echo

        if command -v pvs &>/dev/null; then

            pvs \
                --noheadings \
                -o pv_name,vg_name,pv_size,pv_free 2>/dev/null

        else

            echo "LVM utilities are not available."

        fi


        ##################################################
        # Volume Groups
        ##################################################

        echo
        echo "============================================================"
        echo " LVM - VOLUME GROUPS"
        echo "============================================================"
        echo

        if command -v vgs &>/dev/null; then

            vgs \
                --noheadings \
                -o vg_name,pv_count,lv_count,vg_size,vg_free \
                2>/dev/null

        else

            echo "LVM utilities are not available."

        fi


        ##################################################
        # Logical Volumes
        ##################################################

        echo
        echo "============================================================"
        echo " LVM - LOGICAL VOLUMES"
        echo "============================================================"
        echo

        if command -v lvs &>/dev/null; then

            lvs \
                --noheadings \
                -o lv_name,vg_name,lv_size,lv_attr \
                2>/dev/null

        else

            echo "LVM utilities are not available."

        fi


        ##################################################
        # Swap Information
        ##################################################

        echo
        echo "============================================================"
        echo " SWAP INFORMATION"
        echo "============================================================"
        echo

        if command -v swapon &>/dev/null; then

            swap_data=$(swapon --show 2>/dev/null)

            if [ -n "$swap_data" ]; then

                echo "$swap_data"

            else

                echo "No active swap devices found."

            fi

        else

            echo "'swapon' command is not available."

        fi

        echo
        echo "Memory / Swap Summary:"
        echo "------------------------------------------------------------"

        free -h 2>/dev/null


        ##################################################
        # Filesystem Table
        ##################################################

        echo
        echo "============================================================"
        echo " /etc/fstab"
        echo "============================================================"
        echo

        if [ -r /etc/fstab ]; then

            grep -Ev \
                '^[[:space:]]*(#|$)' \
                /etc/fstab

        else

            echo "Unable to read /etc/fstab."

        fi


        ##################################################
        # Disk Identifiers
        ##################################################

        echo
        echo "============================================================"
        echo " DISK UUID AND FILESYSTEM INFORMATION"
        echo "============================================================"
        echo

        if command -v blkid &>/dev/null; then

            blkid 2>/dev/null

        else

            echo "'blkid' command is not available."

        fi


        ##################################################
        # Disk Usage Health
        ##################################################

        echo
        echo "============================================================"
        echo " DISK USAGE HEALTH"
        echo "============================================================"
        echo

        warning_count=0
        critical_count=0

        while read -r filesystem percent mountpoint
        do

            usage=${percent%\%}

            if [[ ! "$usage" =~ ^[0-9]+$ ]]; then
                continue
            fi

            if [ "$usage" -ge 90 ]; then

                echo "[CRITICAL] $mountpoint - ${usage}% used"
                ((critical_count++))

            elif [ "$usage" -ge 80 ]; then

                echo "[WARNING]  $mountpoint - ${usage}% used"
                ((warning_count++))

            else

                echo "[OK]       $mountpoint - ${usage}% used"

            fi

        done < <(
            df -P \
                -x tmpfs \
                -x devtmpfs \
                -x iso9660 \
                -x squashfs \
                -x overlay \
                2>/dev/null |
            awk 'NR > 1 {print $1, $5, $6}'
        )

        echo
        echo "Critical Filesystems : $critical_count"
        echo "Warning Filesystems  : $warning_count"


        ##################################################
        # Report Footer
        ##################################################

        echo
        echo "============================================================"
        echo "               End of Storage Report"
        echo "============================================================"

    } > "$report_file" 2>&1


    ##################################################
    # Verify Report
    ##################################################

    if [ ! -f "$report_file" ]; then

        error "Storage report could not be created."
        pause
        return

    fi

    if [ ! -s "$report_file" ]; then

        error "Generated report is empty."
        rm -f "$report_file"
        pause
        return

    fi


    ##################################################
    # Report Information
    ##################################################

    report_size=$(du -h "$report_file" |
        awk '{print $1}')

    echo
    success "Storage report generated successfully."

    echo
    echo "Report Name : $report_name"
    echo "Report Path : $report_file"
    echo "Report Size : $report_size"

    pause
}


##################################################
# Function : generate_service_report
# Purpose  : Generate system service report
##################################################

generate_service_report() {

    header

    echo "========== Generate Service Report =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi

    report_name=$(generate_report_name "services")
    report_file="$REPORT_DIR/$report_name"

    echo "Report Type : Services"
    echo "Report File : $report_file"
    echo

    read -p "Generate service report? (Y/N): " confirm

    case "$confirm" in

        Y|y)
            ;;

        N|n)
            warning "Report generation cancelled."
            pause
            return
            ;;

        *)
            error "Invalid choice."
            pause
            return
            ;;
    esac


    ##################################################
    # Generate Report
    ##################################################

    {

        echo "============================================================"
        echo "                LinuxFlow Service Report"
        echo "============================================================"
        echo

        echo "Generated On : $(date '+%d-%m-%Y %H:%M:%S')"
        echo "Generated By : $(whoami)"


        ##################################################
        # Systemd Check
        ##################################################

        echo
        echo "============================================================"
        echo " SYSTEMD INFORMATION"
        echo "============================================================"
        echo

        if ! command -v systemctl &>/dev/null; then

            echo "systemctl command is not available."
            echo
            echo "Unable to generate service information."

        else

            echo "System State : $(systemctl is-system-running 2>/dev/null || echo "unknown")"


            ##################################################
            # Running Services
            ##################################################

            echo
            echo "============================================================"
            echo " RUNNING SERVICES"
            echo "============================================================"
            echo

            systemctl list-units \
                --type=service \
                --state=running \
                --no-pager \
                --no-legend \
                2>/dev/null

            running_count=$(systemctl list-units \
                --type=service \
                --state=running \
                --no-legend \
                --no-pager \
                2>/dev/null |
                awk 'NF {count++} END {print count+0}')

            echo
            echo "Total Running Services : $running_count"


            ##################################################
            # Failed Services
            ##################################################

            echo
            echo "============================================================"
            echo " FAILED SERVICES"
            echo "============================================================"
            echo

            failed_services=$(systemctl \
                --failed \
                --type=service \
                --no-legend \
                --no-pager \
                2>/dev/null)

            if [ -n "$failed_services" ]; then

                echo "$failed_services"

            else

                echo "No failed services found."

            fi

            failed_count=$(systemctl \
                --failed \
                --type=service \
                --no-legend \
                --no-pager \
                2>/dev/null |
                awk 'NF {count++} END {print count+0}')

            echo
            echo "Total Failed Services : $failed_count"


            ##################################################
            # Enabled Services
            ##################################################

            echo
            echo "============================================================"
            echo " ENABLED SERVICES"
            echo "============================================================"
            echo

            systemctl list-unit-files \
                --type=service \
                --state=enabled \
                --no-pager \
                --no-legend \
                2>/dev/null

            enabled_count=$(systemctl list-unit-files \
                --type=service \
                --state=enabled \
                --no-pager \
                --no-legend \
                2>/dev/null |
                awk 'NF {count++} END {print count+0}')

            echo
            echo "Total Enabled Services : $enabled_count"


            ##################################################
            # Disabled Services
            ##################################################

            echo
            echo "============================================================"
            echo " DISABLED SERVICES"
            echo "============================================================"
            echo

            systemctl list-unit-files \
                --type=service \
                --state=disabled \
                --no-pager \
                --no-legend \
                2>/dev/null

            disabled_count=$(systemctl list-unit-files \
                --type=service \
                --state=disabled \
                --no-pager \
                --no-legend \
                2>/dev/null |
                awk 'NF {count++} END {print count+0}')

            echo
            echo "Total Disabled Services : $disabled_count"


            ##################################################
            # Failed Service Details
            ##################################################

            echo
            echo "============================================================"
            echo " FAILED SERVICE DETAILS"
            echo "============================================================"
            echo

            if [ "$failed_count" -gt 0 ]; then

                while read -r service
                do

                    [ -z "$service" ] && continue

                    echo
                    echo "------------------------------------------------------------"
                    echo "Service : $service"
                    echo "------------------------------------------------------------"
                    echo

                    systemctl status "$service" \
                        --no-pager \
                        -l \
                        2>/dev/null || true

                done < <(
                    systemctl \
                        --failed \
                        --type=service \
                        --no-legend \
                        --no-pager \
                        2>/dev/null |
                    awk '{print $1}'
                )

            else

                echo "No failed service details to display."

            fi


            ##################################################
            # Important Service Status
            ##################################################

            echo
            echo "============================================================"
            echo " IMPORTANT SERVICE STATUS"
            echo "============================================================"
            echo

            important_services=(
                "sshd"
                "firewalld"
                "crond"
            )

            printf "%-20s %-15s %-15s\n" \
                "SERVICE" "ACTIVE" "ENABLED"

            printf "%-20s %-15s %-15s\n" \
                "--------------------" \
                "---------------" \
                "---------------"

            for service in "${important_services[@]}"
            do

                if systemctl list-unit-files \
                    "${service}.service" \
                    --no-legend 2>/dev/null |
                    grep -q "^${service}.service"; then

                    active=$(systemctl is-active \
                        "$service" 2>/dev/null)

                    enabled=$(systemctl is-enabled \
                        "$service" 2>/dev/null)

                    printf "%-20s %-15s %-15s\n" \
                        "$service" \
                        "${active:-unknown}" \
                        "${enabled:-unknown}"

                else

                    printf "%-20s %-15s %-15s\n" \
                        "$service" \
                        "not-installed" \
                        "-"

                fi

            done


            ##################################################
            # Service Health Summary
            ##################################################

            echo
            echo "============================================================"
            echo " SERVICE HEALTH SUMMARY"
            echo "============================================================"
            echo

            echo "Running Services  : $running_count"
            echo "Enabled Services  : $enabled_count"
            echo "Disabled Services : $disabled_count"
            echo "Failed Services   : $failed_count"

            echo

            if [ "$failed_count" -gt 0 ]; then

                echo "[WARNING] One or more system services have failed."

            else

                echo "[OK] No failed system services detected."

            fi

        fi


        ##################################################
        # Report Footer
        ##################################################

        echo
        echo "============================================================"
        echo "               End of Service Report"
        echo "============================================================"

    } > "$report_file" 2>&1


    ##################################################
    # Verify Report
    ##################################################

    if [ ! -f "$report_file" ]; then

        error "Service report could not be created."
        pause
        return

    fi

    if [ ! -s "$report_file" ]; then

        error "Generated report is empty."
        rm -f "$report_file"
        pause
        return

    fi


    ##################################################
    # Report Information
    ##################################################

    report_size=$(du -h "$report_file" |
        awk '{print $1}')

    echo
    success "Service report generated successfully."

    echo
    echo "Report Name : $report_name"
    echo "Report Path : $report_file"
    echo "Report Size : $report_size"

    pause
}



##################################################
# Function : generate_security_report
# Purpose  : Generate system security report
##################################################

generate_security_report() {

    header

    echo "========== Generate Security Report =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi

    report_name=$(generate_report_name "security")
    report_file="$REPORT_DIR/$report_name"

    echo "Report Type : Security"
    echo "Report File : $report_file"
    echo

    read -p "Generate security report? (Y/N): " confirm

    case "$confirm" in

        Y|y)
            ;;

        N|n)
            warning "Report generation cancelled."
            pause
            return
            ;;

        *)
            error "Invalid choice."
            pause
            return
            ;;
    esac


    ##################################################
    # Generate Report
    ##################################################

    {

        echo "============================================================"
        echo "               LinuxFlow Security Report"
        echo "============================================================"
        echo

        echo "Generated On : $(date '+%d-%m-%Y %H:%M:%S')"
        echo "Generated By : $(whoami)"


        ##################################################
        # SELinux
        ##################################################

        echo
        echo "============================================================"
        echo " SELINUX STATUS"
        echo "============================================================"
        echo

        if command -v getenforce &>/dev/null; then

            echo "Current Mode : $(getenforce)"

            if command -v sestatus &>/dev/null; then
                echo
                sestatus
            fi

        else

            echo "SELinux utilities are not available."

        fi


        ##################################################
        # Firewall Status
        ##################################################

        echo
        echo "============================================================"
        echo " FIREWALL STATUS"
        echo "============================================================"
        echo

        if command -v firewall-cmd &>/dev/null; then

            if systemctl is-active --quiet firewalld 2>/dev/null; then

                echo "Firewalld Status : Active"

                firewall_zone=$(firewall-cmd \
                    --get-default-zone 2>/dev/null)

                echo "Default Zone     : ${firewall_zone:-Unknown}"

                echo
                echo "Active Zones:"
                echo "------------------------------------------------------------"

                firewall-cmd --get-active-zones 2>/dev/null

                echo
                echo "Firewall Configuration:"
                echo "------------------------------------------------------------"

                firewall-cmd --list-all 2>/dev/null

            else

                echo "Firewalld Status : Inactive"

            fi

        else

            echo "firewall-cmd is not available."

        fi


        ##################################################
        # SSH Security
        ##################################################

        echo
        echo "============================================================"
        echo " SSH SECURITY"
        echo "============================================================"
        echo

        if command -v sshd &>/dev/null; then

            ssh_service=""

            if systemctl list-unit-files sshd.service \
                --no-legend 2>/dev/null |
                grep -q '^sshd.service'; then

                ssh_service="sshd"

            elif systemctl list-unit-files ssh.service \
                --no-legend 2>/dev/null |
                grep -q '^ssh.service'; then

                ssh_service="ssh"

            fi

            if [ -n "$ssh_service" ]; then

                echo "SSH Service : $ssh_service"
                echo "Active      : $(systemctl is-active "$ssh_service" 2>/dev/null)"
                echo "Enabled     : $(systemctl is-enabled "$ssh_service" 2>/dev/null)"

            else

                echo "SSH systemd service could not be detected."

            fi

            echo

            if sshd -t 2>/dev/null; then

                ssh_config=$(sshd -T 2>/dev/null)

                echo "Effective SSH Configuration:"
                echo "------------------------------------------------------------"

                echo "Port                  : $(echo "$ssh_config" |
                    awk '$1=="port" {print $2; exit}')"

                echo "Permit Root Login     : $(echo "$ssh_config" |
                    awk '$1=="permitrootlogin" {print $2; exit}')"

                echo "Password Authentication : $(echo "$ssh_config" |
                    awk '$1=="passwordauthentication" {print $2; exit}')"

                echo "Public Key Authentication: $(echo "$ssh_config" |
                    awk '$1=="pubkeyauthentication" {print $2; exit}')"

                echo "Permit Empty Passwords: $(echo "$ssh_config" |
                    awk '$1=="permitemptypasswords" {print $2; exit}')"

                echo "Max Authentication Tries: $(echo "$ssh_config" |
                    awk '$1=="maxauthtries" {print $2; exit}')"

            else

                echo "SSH configuration contains errors or could not be validated."

            fi

        else

            echo "OpenSSH Server is not installed."

        fi


        ##################################################
        # Listening Network Ports
        ##################################################

        echo
        echo "============================================================"
        echo " LISTENING NETWORK PORTS"
        echo "============================================================"
        echo

        if command -v ss &>/dev/null; then

            ss -lntup 2>/dev/null

        else

            echo "'ss' command is not available."

        fi


        ##################################################
        # Logged In Users
        ##################################################

        echo
        echo "============================================================"
        echo " CURRENT LOGIN SESSIONS"
        echo "============================================================"
        echo

        if command -v who &>/dev/null; then

            login_data=$(who 2>/dev/null)

            if [ -n "$login_data" ]; then
                echo "$login_data"
            else
                echo "No active login sessions."
            fi

        else

            echo "'who' command is not available."

        fi


        ##################################################
        # Recent Successful Logins
        ##################################################

        echo
        echo "============================================================"
        echo " RECENT LOGIN HISTORY"
        echo "============================================================"
        echo

        if command -v last &>/dev/null; then

            last -n 10 2>/dev/null

        else

            echo "'last' command is not available."

        fi


      ##################################################
# Failed Login Attempts
##################################################

echo
echo "============================================================"
echo " RECENT FAILED LOGIN ATTEMPTS"
echo "============================================================"
echo

failed_logins=""

if command -v lastb &>/dev/null; then

    failed_logins=$(lastb -n 10 2>/dev/null |
        grep -v '^btmp begins' |
        grep -v '^[[:space:]]*$')

    if [ -n "$failed_logins" ]; then
        echo "$failed_logins"
    else
        echo "No recent failed login attempts found."
    fi

else

    echo "'lastb' command is not available."

fi



        ##################################################
        # Locked Normal User Accounts
        ##################################################

        echo
        echo "============================================================"
        echo " LOCKED NORMAL USER ACCOUNTS"
        echo "============================================================"
        echo

        locked_count=0

        while IFS=: read -r username _ uid _ _
        do

            if [ "$uid" -lt 1000 ] ||
               [ "$uid" -ge 65534 ]; then
                continue
            fi

            account_state=$(passwd -S "$username" 2>/dev/null |
                awk '{print $2}')

            if [ "$account_state" = "L" ] ||
               [ "$account_state" = "LK" ]; then

                echo "$username"
                ((locked_count++))
            fi

        done < /etc/passwd

        if [ "$locked_count" -eq 0 ]; then
            echo "No locked normal user accounts found."
        fi

        echo
        echo "Total Locked Users : $locked_count"


        ##################################################
        # Administrative Group
        ##################################################

        echo
        echo "============================================================"
        echo " ADMINISTRATIVE USERS"
        echo "============================================================"
        echo

        if getent group wheel &>/dev/null; then

            echo "Administrative Group : wheel"

            wheel_members=$(getent group wheel |
                awk -F: '{print $4}')

            if [ -n "$wheel_members" ]; then

                echo "Supplementary Members:"
                echo "$wheel_members" | tr ',' '\n'

            else

                echo "No supplementary wheel members."

            fi

        elif getent group sudo &>/dev/null; then

            echo "Administrative Group : sudo"

            sudo_members=$(getent group sudo |
                awk -F: '{print $4}')

            if [ -n "$sudo_members" ]; then

                echo "Supplementary Members:"
                echo "$sudo_members" | tr ',' '\n'

            else

                echo "No supplementary sudo members."

            fi

        else

            echo "No wheel/sudo administrative group detected."

        fi


        ##################################################
        # SUID Files
        ##################################################

        echo
        echo "============================================================"
        echo " SUID EXECUTABLE FILES"
        echo "============================================================"
        echo

        echo "Files with the SUID permission bit:"
        echo "------------------------------------------------------------"

        find / \
            -xdev \
            -type f \
            -perm -4000 \
            -print \
            2>/dev/null |
            sort


        ##################################################
        # World Writable Directories
        ##################################################

        echo
        echo "============================================================"
        echo " WORLD-WRITABLE DIRECTORIES"
        echo "============================================================"
        echo

        echo "World-writable directories on the root filesystem:"
        echo "------------------------------------------------------------"

        find / \
            -xdev \
            -type d \
            -perm -0002 \
            -print \
            2>/dev/null |
            sort


        ##################################################
        # Security Summary
        ##################################################

        echo
        echo "============================================================"
        echo " SECURITY SUMMARY"
        echo "============================================================"
        echo

        if command -v getenforce &>/dev/null; then
            echo "SELinux       : $(getenforce)"
        else
            echo "SELinux       : Unknown"
        fi

        if command -v firewall-cmd &>/dev/null; then

            if systemctl is-active --quiet firewalld 2>/dev/null; then
                echo "Firewall      : Active"
            else
                echo "Firewall      : Inactive"
            fi

        else

            echo "Firewall      : Not Available"

        fi

        if command -v sshd &>/dev/null; then
            echo "SSH Server    : Installed"
        else
            echo "SSH Server    : Not Installed"
        fi

        echo "Locked Users  : $locked_count"

        if [ -n "$failed_logins" ]; then
            echo "Failed Logins : Detected"
        else
            echo "Failed Logins : None Detected"
        fi


        ##################################################
        # Report Footer
        ##################################################

        echo
        echo "============================================================"
        echo "              End of Security Report"
        echo "============================================================"

    } > "$report_file" 2>&1


    ##################################################
    # Verify Report
    ##################################################

    if [ ! -f "$report_file" ]; then

        error "Security report could not be created."
        pause
        return

    fi

    if [ ! -s "$report_file" ]; then

        error "Generated report is empty."
        rm -f "$report_file"
        pause
        return

    fi


    ##################################################
    # Report Information
    ##################################################

    report_size=$(du -h "$report_file" |
        awk '{print $1}')

    echo
    success "Security report generated successfully."

    echo
    echo "Report Name : $report_name"
    echo "Report Path : $report_file"
    echo "Report Size : $report_size"

    pause
}



##################################################
# Function : generate_full_report
