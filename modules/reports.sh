generate_full_report() {

    header

    echo "========== Generate Full System Report =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi

    report_name=$(generate_report_name "full")
    report_file="$REPORT_DIR/$report_name"

    echo "Report Type : Full System Report"
    echo "Report File : $report_file"
    echo

    warning "This report may take a few seconds to generate."
    echo

    read -p "Generate full system report? (Y/N): " confirm

    case "$confirm" in

        Y|y)
            ;;

        N|n)
            warning "Report generation cancelled."
            pause
            return
            ;;

        *)
            error "Invalid choice."
            pause
            return
            ;;
    esac

    echo
    echo "Collecting system information..."


    ##################################################
    # Generate Full Report
    ##################################################

    {

        echo "============================================================"
        echo "               LinuxFlow Full System Report"
        echo "============================================================"
        echo

        echo "Generated On : $(date '+%d-%m-%Y %H:%M:%S')"
        echo "Generated By : $(whoami)"
        echo "Hostname     : $(hostname)"

        echo


        ##################################################
        # 1. System Information
        ##################################################

        echo "============================================================"
        echo " 1. SYSTEM INFORMATION"
        echo "============================================================"
        echo

        echo "Hostname     : $(hostname)"
        echo "Kernel       : $(uname -r)"
        echo "Architecture : $(uname -m)"

        if [ -r /etc/os-release ]; then

            os_name=$(awk -F= '
                /^PRETTY_NAME=/ {
                    gsub(/"/, "", $2)
                    print $2
                    exit
                }
            ' /etc/os-release)

            echo "Operating System : ${os_name:-Unknown}"

        else

            echo "Operating System : Unknown"

        fi

        echo "Uptime           : $(uptime -p 2>/dev/null || echo "Unknown")"
        echo "Boot Time        : $(uptime -s 2>/dev/null || echo "Unknown")"


        ##################################################
        # 2. CPU Information
        ##################################################

        echo
        echo "============================================================"
        echo " 2. CPU INFORMATION"
        echo "============================================================"
        echo

        echo "CPU Cores : $(nproc 2>/dev/null || echo "Unknown")"

        cpu_model=$(awk -F: '
            /model name/ {
                gsub(/^[ \t]+/, "", $2)
                print $2
                exit
            }
        ' /proc/cpuinfo 2>/dev/null)

        echo "CPU Model : ${cpu_model:-Unknown}"

        if [ -r /proc/loadavg ]; then

            read -r load1 load5 load15 _ < /proc/loadavg

            echo
            echo "Load Average:"
            echo "1 Minute   : $load1"
            echo "5 Minutes  : $load5"
            echo "15 Minutes : $load15"

        fi


        ##################################################
        # 3. Memory and Swap
        ##################################################

        echo
        echo "============================================================"
        echo " 3. MEMORY AND SWAP"
        echo "============================================================"
        echo

        free -h 2>/dev/null

        echo
        echo "Active Swap:"
        echo "------------------------------------------------------------"

        if command -v swapon &>/dev/null; then

            swap_data=$(swapon --show 2>/dev/null)

            if [ -n "$swap_data" ]; then
                echo "$swap_data"
            else
                echo "No active swap configured."
            fi

        else

            echo "'swapon' command is not available."

        fi


        ##################################################
        # 4. Storage
        ##################################################

        echo
        echo "============================================================"
        echo " 4. STORAGE INFORMATION"
        echo "============================================================"
        echo

        echo "Block Devices:"
        echo "------------------------------------------------------------"

        if command -v lsblk &>/dev/null; then

            lsblk -o \
                NAME,SIZE,TYPE,FSTYPE,FSAVAIL,FSUSE%,MOUNTPOINTS

        else

            echo "'lsblk' command is not available."

        fi

        echo
        echo "Filesystem Usage:"
        echo "------------------------------------------------------------"

        df -hP \
            -x tmpfs \
            -x devtmpfs \
            -x iso9660 \
            -x squashfs \
            -x overlay \
            2>/dev/null


        ##################################################
        # 5. LVM
        ##################################################

        echo
        echo "============================================================"
        echo " 5. LVM INFORMATION"
        echo "============================================================"
        echo

        echo "Physical Volumes:"
        echo "------------------------------------------------------------"

        if command -v pvs &>/dev/null; then
            pvs 2>/dev/null
        else
            echo "LVM utilities are not available."
        fi

        echo
        echo "Volume Groups:"
        echo "------------------------------------------------------------"

        if command -v vgs &>/dev/null; then
            vgs 2>/dev/null
        else
            echo "LVM utilities are not available."
        fi

        echo
        echo "Logical Volumes:"
        echo "------------------------------------------------------------"

        if command -v lvs &>/dev/null; then
            lvs 2>/dev/null
        else
            echo "LVM utilities are not available."
        fi


        ##################################################
        # 6. Users
        ##################################################

        echo
        echo "============================================================"
        echo " 6. USER INFORMATION"
        echo "============================================================"
        echo

        printf "%-20s %-10s %-25s %s\n" \
            "USERNAME" "UID" "HOME" "SHELL"

        printf "%-20s %-10s %-25s %s\n" \
            "--------------------" \
            "----------" \
            "-------------------------" \
            "--------------------"

        awk -F: '
            $3 >= 1000 && $3 < 65534 {
                printf "%-20s %-10s %-25s %s\n",
                $1, $3, $6, $7
            }
        ' /etc/passwd

        total_users=$(awk -F: '
            $3 >= 1000 && $3 < 65534 {
                count++
            }

            END {
                print count+0
            }
        ' /etc/passwd)

        echo
        echo "Total Normal Users : $total_users"


        ##################################################
        # 7. Groups
        ##################################################

        echo
        echo "============================================================"
        echo " 7. GROUP INFORMATION"
        echo "============================================================"
        echo

        printf "%-25s %-10s %s\n" \
            "GROUP NAME" "GID" "MEMBERS"

        awk -F: '{
            members=$4

            if (members == "")
                members="None"

            printf "%-25s %-10s %s\n",
            $1, $3, members
        }' /etc/group

        total_groups=$(awk 'END {print NR}' /etc/group)

        echo
        echo "Total Groups : $total_groups"


        ##################################################
        # 8. Logged In Users
        ##################################################

        echo
        echo "============================================================"
        echo " 8. ACTIVE LOGIN SESSIONS"
        echo "============================================================"
        echo

        if command -v who &>/dev/null; then

            login_data=$(who 2>/dev/null)

            if [ -n "$login_data" ]; then
                echo "$login_data"
            else
                echo "No active login sessions."
            fi

        else

            echo "'who' command is not available."

        fi


        ##################################################
        # 9. Network
        ##################################################

        echo
        echo "============================================================"
        echo " 9. NETWORK INFORMATION"
        echo "============================================================"
        echo

        if command -v ip &>/dev/null; then

            echo "Interfaces:"
            echo "------------------------------------------------------------"

            ip -brief address 2>/dev/null

            echo
            echo "Default Route:"
            echo "------------------------------------------------------------"

            ip route show default 2>/dev/null

        else

            echo "'ip' command is not available."

        fi

        echo
        echo "Listening Ports:"
        echo "------------------------------------------------------------"

        if command -v ss &>/dev/null; then
            ss -lntup 2>/dev/null
        else
            echo "'ss' command is not available."
        fi


        ##################################################
        # 10. Services
        ##################################################

        echo
        echo "============================================================"
        echo " 10. SERVICE INFORMATION"
        echo "============================================================"
        echo

        if command -v systemctl &>/dev/null; then

            running_services=$(systemctl list-units \
                --type=service \
                --state=running \
                --no-legend \
                --no-pager \
                2>/dev/null |
                awk 'NF {count++} END {print count+0}')

            failed_services=$(systemctl \
                --failed \
                --type=service \
                --no-legend \
                --no-pager \
                2>/dev/null |
                awk 'NF {count++} END {print count+0}')

            echo "Running Services : $running_services"
            echo "Failed Services  : $failed_services"

            echo
            echo "Failed Service List:"
            echo "------------------------------------------------------------"

            if [ "$failed_services" -gt 0 ]; then

                systemctl \
                    --failed \
                    --type=service \
                    --no-pager \
                    2>/dev/null

            else

                echo "No failed services detected."

            fi

        else

            echo "'systemctl' command is not available."

        fi


        ##################################################
        # 11. Firewall
        ##################################################

        echo
        echo "============================================================"
        echo " 11. FIREWALL"
        echo "============================================================"
        echo

        if command -v firewall-cmd &>/dev/null; then

            if systemctl is-active --quiet firewalld 2>/dev/null; then

                echo "Firewalld Status : Active"
                echo

                firewall-cmd --get-active-zones 2>/dev/null

                echo
                firewall-cmd --list-all 2>/dev/null

            else

                echo "Firewalld Status : Inactive"

            fi

        else

            echo "Firewalld is not available."

        fi


        ##################################################
        # 12. SELinux
        ##################################################

        echo
        echo "============================================================"
        echo " 12. SELINUX"
        echo "============================================================"
        echo

        if command -v getenforce &>/dev/null; then

            echo "SELinux Mode : $(getenforce)"

            if command -v sestatus &>/dev/null; then
                echo
                sestatus
            fi

        else

            echo "SELinux information is unavailable."

        fi


        ##################################################
        # 13. SSH
        ##################################################

        echo
        echo "============================================================"
        echo " 13. SSH INFORMATION"
        echo "============================================================"
        echo

        if command -v sshd &>/dev/null; then

            if sshd -t 2>/dev/null; then

                ssh_config=$(sshd -T 2>/dev/null)

                echo "Port              : $(echo "$ssh_config" |
                    awk '$1=="port" {print $2; exit}')"

                echo "Root Login        : $(echo "$ssh_config" |
                    awk '$1=="permitrootlogin" {print $2; exit}')"

                echo "Password Auth     : $(echo "$ssh_config" |
                    awk '$1=="passwordauthentication" {print $2; exit}')"

                echo "Public Key Auth   : $(echo "$ssh_config" |
                    awk '$1=="pubkeyauthentication" {print $2; exit}')"

            else

                echo "SSH configuration validation failed."

            fi

        else

            echo "OpenSSH Server is not installed."

        fi


        ##################################################
        # 14. Failed Logins
        ##################################################

        echo
        echo "============================================================"
        echo " 14. RECENT FAILED LOGIN ATTEMPTS"
        echo "============================================================"
        echo

        failed_login_data=""

        if command -v lastb &>/dev/null; then

            failed_login_data=$(lastb -n 10 2>/dev/null |
                grep -v '^btmp begins' |
                grep -v '^[[:space:]]*$')

            if [ -n "$failed_login_data" ]; then
                echo "$failed_login_data"
            else
                echo "No recent failed login attempts found."
            fi

        else

            echo "'lastb' command is not available."

        fi


        ##################################################
        # 15. Cron
        ##################################################

        echo
        echo "============================================================"
        echo " 15. CRON INFORMATION"
        echo "============================================================"
        echo

        if command -v systemctl &>/dev/null; then

            if systemctl list-unit-files crond.service \
                --no-legend 2>/dev/null |
                grep -q '^crond.service'; then

                echo "Cron Service Active  : $(systemctl is-active crond 2>/dev/null)"
                echo "Cron Service Enabled : $(systemctl is-enabled crond 2>/dev/null)"

            fi

        fi

        echo
        echo "Current User Crontab:"
        echo "------------------------------------------------------------"

        if command -v crontab &>/dev/null; then

            crontab_data=$(crontab -l 2>/dev/null)

            if [ -n "$crontab_data" ]; then
                echo "$crontab_data"
            else
                echo "No crontab entries for current user."
            fi

        else

            echo "'crontab' command is not available."

        fi


        ##################################################
        # 16. /etc/fstab
        ##################################################

        echo
        echo "============================================================"
        echo " 16. FILESYSTEM TABLE"
        echo "============================================================"
        echo

        if [ -r /etc/fstab ]; then

            grep -Ev \
                '^[[:space:]]*(#|$)' \
                /etc/fstab

        else

            echo "Unable to read /etc/fstab."

        fi


        ##################################################
        # 17. Overall Summary
        ##################################################

        echo
        echo "============================================================"
        echo " 17. SYSTEM SUMMARY"
        echo "============================================================"
        echo

        echo "Hostname         : $(hostname)"
        echo "Normal Users     : ${total_users:-0}"
        echo "Groups           : ${total_groups:-0}"
        echo "Running Services : ${running_services:-Unknown}"
        echo "Failed Services  : ${failed_services:-Unknown}"

        if command -v getenforce &>/dev/null; then
            echo "SELinux          : $(getenforce)"
        else
            echo "SELinux          : Unknown"
        fi

        if command -v firewall-cmd &>/dev/null &&
           systemctl is-active --quiet firewalld 2>/dev/null; then

            echo "Firewall         : Active"

        else

            echo "Firewall         : Inactive / Unavailable"

        fi

        if [ -n "$failed_login_data" ]; then
            echo "Failed Logins    : Detected"
        else
            echo "Failed Logins    : None Detected"
        fi


        ##################################################
        # Footer
        ##################################################

        echo
        echo "============================================================"
        echo "            End of LinuxFlow Full Report"
        echo "============================================================"

    } > "$report_file" 2>&1


    ##################################################
    # Verify Report
    ##################################################

    if [ ! -f "$report_file" ]; then

        error "Full system report could not be created."
        pause
        return

    fi

    if [ ! -s "$report_file" ]; then

        error "Generated report is empty."
        rm -f "$report_file"
        pause
        return

    fi


    ##################################################
    # Report Information
    ##################################################

    report_size=$(du -h "$report_file" |
        awk '{print $1}')

    report_lines=$(wc -l < "$report_file")

    echo
    success "Full system report generated successfully."

    echo
    echo "Report Name  : $report_name"
    echo "Report Path  : $report_file"
    echo "Report Size  : $report_size"
    echo "Report Lines : $report_lines"

    pause
}



##################################################
# Function : view_reports
# Purpose  : List and view generated reports
##################################################

view_reports() {

    header

    echo "========== View Generated Reports =========="
    echo

    if ! initialize_report_directory; then
        pause
        return
    fi


    ##################################################
    # Load Available Reports
    ##################################################

    reports=()

    while IFS= read -r file
    do
        reports+=("$file")
    done < <(
        find "$REPORT_DIR" \
            -maxdepth 1 \
            -type f \
            -name "linuxflow_*.txt" \
            -printf "%T@ %p\n" 2>/dev/null |
        sort -nr |
        cut -d' ' -f2-
    )


    ##################################################
    # Check Reports
    ##################################################

    if [ "${#reports[@]}" -eq 0 ]; then

        warning "No generated reports found."
        pause
        return

    fi


    ##################################################
    # Display Report List
    ##################################################

    echo "Available Reports:"
    echo

    printf "%-5s %-45s %-10s %-20s\n" \
        "NO." \
        "REPORT NAME" \
        "SIZE" \
        "CREATED"

    printf "%-5s %-45s %-10s %-20s\n" \
        "-----" \
        "---------------------------------------------" \
        "----------" \
        "--------------------"

    index=1

    for file in "${reports[@]}"
    do

        filename=$(basename "$file")

        size=$(du -h "$file" 2>/dev/null |
            awk '{print $1}')

        created=$(date -r "$file" \
            "+%d-%m-%Y %H:%M:%S" 2>/dev/null)

        printf "%-5s %-45s %-10s %-20s\n" \
            "$index" \
            "$filename" \
            "${size:-Unknown}" \
            "${created:-Unknown}"

        ((index++))

    done

    echo
    echo "Total Reports : ${#reports[@]}"
    echo


    ##################################################
    # Select Report
    ##################################################

    read -p "Enter report number to view (0 to cancel): " choice

    if [ "$choice" = "0" ]; then

        warning "Operation cancelled."
        pause
        return

    fi


    ##################################################
    # Validate Selection
    ##################################################

    if [[ ! "$choice" =~ ^[0-9]+$ ]]; then

        error "Invalid report number."
        pause
        return

    fi

    if [ "$choice" -lt 1 ] ||
       [ "$choice" -gt "${#reports[@]}" ]; then

        error "Report number is out of range."
        pause
        return

    fi


    ##################################################
    # Get Selected Report
    ##################################################

    selected_report="${reports[$((choice - 1))]}"

    if [ ! -f "$selected_report" ]; then

        error "Selected report no longer exists."
        pause
        return

    fi

    if [ ! -r "$selected_report" ]; then

        error "Selected report cannot be read."
        pause
        return

    fi


    ##################################################
    # Display Selected Report
    ##################################################

    header

    echo "========== Report Viewer =========="
    echo
    echo "Report : $(basename "$selected_report")"
    echo
    echo "----------------------------------------------"
    echo

    if command -v less &>/dev/null; then

        less "$selected_report"

    elif command -v more &>/dev/null; then

        more "$selected_report"

    else

        cat "$selected_report"

    fi

    pause
}



